static void test_hashes(void) {
    static const char* const empty = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";
    static const char* const abc = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";
    static const char* const two_blocks = "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1";
    static const char* const million_a = "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0";
    static const char msg[] = "abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
    uint8_t digest[32];
    char hex[65];
    uint8_t a[1000];
    KoSha256 s;
    size_t i;

    ko_sha256_init(&s);
    ko_sha256_final(&s, digest);
    ko_sha256_hex(digest, hex);
    CHECK(strcmp(hex, empty) == 0);

    ko_sha256_init(&s);
    ko_sha256_update(&s, "abc", 3);
    ko_sha256_final(&s, digest);
    ko_sha256_hex(digest, hex);
    CHECK(strcmp(hex, abc) == 0);

    /* in uneven pieces */
    ko_sha256_init(&s);
    for (i = 0; i < sizeof(msg) - 1; i += 5) {
        ko_sha256_update(&s, msg + i, sizeof(msg) - 1 - i < 5 ? sizeof(msg) - 1 - i : 5);
    }
    ko_sha256_final(&s, digest);
    ko_sha256_hex(digest, hex);
    CHECK(strcmp(hex, two_blocks) == 0);

    memset(a, 'a', sizeof(a));
    ko_sha256_init(&s);
    for (i = 0; i < 1000; i++) {
        ko_sha256_update(&s, a, sizeof(a));
    }
    ko_sha256_final(&s, digest);
    ko_sha256_hex(digest, hex);
    CHECK(strcmp(hex, million_a) == 0);

    CHECK(ko_adler32(1, (const uint8_t*)"Wikipedia", 9) == 0x11E60398);
    CHECK(ko_crc32(0, (const uint8_t*)"123456789", 9) == 0xCBF43926);
    /* Adler-32 sums past the 5552-byte chunk */
    {
        uint8_t big[20000];
        uint32_t whole, parts;

        make_text(big, sizeof(big), 3);
        whole = ko_adler32(1, big, sizeof(big));
        parts = ko_adler32(ko_adler32(1, big, 7000), big + 7000, sizeof(big) - 7000);
        CHECK(whole == parts);
    }
}

static void test_inflate(void) {
    static const uint8_t stored[] = { 0x01, 0x05, 0x00, 0xFA, 0xFF, 'h', 'e', 'l', 'l', 'o' };
    uint8_t text[4000];
    uint8_t out[4000];

    make_text(text, sizeof(text), 1);

    CHECK(ko_inflate(stored, sizeof(stored), out, 5) && memcmp(out, "hello", 5) == 0);
    CHECK(!ko_inflate(stored, sizeof(stored), out, 4)); /* too small */
    CHECK(!ko_inflate(stored, sizeof(stored) - 1, out, 5)); /* cut short */

    memset(out, 0, sizeof(out));
    CHECK(ko_inflate(deflate_fixed, sizeof(deflate_fixed), out, sizeof(out)));
    CHECK(memcmp(out, text, sizeof(text)) == 0);

    memset(out, 0, sizeof(out));
    CHECK(ko_inflate(deflate_dynamic, sizeof(deflate_dynamic), out, sizeof(out)));
    CHECK(memcmp(out, text, sizeof(text)) == 0);

    CHECK(!ko_inflate(deflate_dynamic, sizeof(deflate_dynamic) / 2, out, sizeof(out)));
}

static void test_zip(void) {
    uint8_t text[3000];
    uint8_t* data;
    size_t len = 0;
    char name[64];
    char json[256];
    char value[32];
    uint64_t n = 0;

    make_text(text, sizeof(text), 7);

    data = ko_zip_extract(zip_file, sizeof(zip_file), ".xdelta", &len, name, sizeof(name));
    CHECK(data != NULL && len == sizeof(text) && memcmp(data, text, len) == 0);
    CHECK(strcmp(name, "Patch-v1/Game.XDELTA") == 0);
    free(data);

    data = ko_zip_extract(zip_file, sizeof(zip_file), "readme.txt", &len, NULL, 0);
    CHECK(data != NULL && len == 20 && memcmp(data, "hello, stored entry\n", 20) == 0);
    free(data);

    CHECK(ko_zip_extract(zip_file, sizeof(zip_file), ".iso", &len, NULL, 0) == NULL);
    CHECK(ko_zip_extract(zip_file, 100, ".xdelta", &len, NULL, 0) == NULL);

    /* a damaged entry fails its CRC */
    {
        uint8_t broken[sizeof(zip_file)];

        memcpy(broken, zip_file, sizeof(broken));
        broken[60] ^= 0x40; /* inside readme.txt's data */
        CHECK(ko_zip_extract(broken, sizeof(broken), "readme.txt", &len, NULL, 0) == NULL);
    }

    data = ko_zip_extract(zip_file, sizeof(zip_file), "manifest.json", &len, NULL, 0);
    CHECK(data != NULL && len < sizeof(json));
    if (data != NULL && len < sizeof(json)) {
        memcpy(json, data, len);
        json[len] = '\0';
        CHECK(ko_json_string(json, "version", value, sizeof(value)) && strcmp(value, "v1") == 0);
        CHECK(ko_json_string(json, "note", value, sizeof(value)) && strcmp(value, "say \"hi\"") == 0);
        CHECK(ko_json_u64(json, "target_bytes", &n) && n == 4567);
        CHECK(!ko_json_u64(json, "version", &n));
        CHECK(!ko_json_string(json, "missing", value, sizeof(value)));
        /* "v1" is a value, not a key */
        CHECK(!ko_json_string(json, "v1", value, sizeof(value)));
    }
    free(data);
}

