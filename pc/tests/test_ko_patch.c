typedef struct {
    uint8_t buf[8192];
    size_t len;
    int fail_write;
} Out;

static int mem_read(void* user, uint64_t offset, uint8_t* dst, size_t len) {
    Mem* m = (Mem*)user;

    if (offset > m->len || len > m->len - offset) {
        return 0;
    }
    memcpy(dst, m->data + offset, len);
    return 1;
}

static int out_write(void* user, const uint8_t* src, size_t len) {
    Out* o = (Out*)user;

    if (o->fail_write || len > sizeof(o->buf) - o->len) {
        return 0;
    }
    memcpy(o->buf + o->len, src, len);
    o->len += len;
    return 1;
}

static int out_read(void* user, uint64_t offset, uint8_t* dst, size_t len) {
    Out* o = (Out*)user;

    if (offset > o->len || len > o->len - offset) {
        return 0;
    }
    memcpy(dst, o->buf + offset, len);
    return 1;
}

static uint64_t progress_done;
static uint64_t progress_total;

static void progress(void* user, uint64_t done, uint64_t total) {
    (void)user;
    progress_done = done;
    progress_total = total;
}

static void test_vcdiff(void) {
    uint8_t src[6000];
    uint8_t target[4712];
    uint8_t wrong[6000];
    size_t t = 0;
    uint64_t size = 0;
    Mem source = { src, sizeof(src) };
    static Out out;
    KoVcdiffIo io;
    int i;
    volatile int cancel = 0;

    make_text(src, sizeof(src), 1);
    /* src[:1000] + "KOREAN PATCH" + src[1500:4000] + bytes 0-199 + src[100:900] + "zzzz" x 50 */
    memcpy(target + t, src, 1000);
    t += 1000;
    memcpy(target + t, "KOREAN PATCH", 12);
    t += 12;
    memcpy(target + t, src + 1500, 2500);
    t += 2500;
    for (i = 0; i < 200; i++) {
        target[t++] = (uint8_t)i;
    }
    memcpy(target + t, src + 100, 800);
    t += 800;
    for (i = 0; i < 50; i++) {
        memcpy(target + t, "zzzz", 4);
        t += 4;
    }
    CHECK(t == sizeof(target));

    CHECK(ko_vcdiff_target_size(xdelta_patch, sizeof(xdelta_patch), &size) == KO_VCDIFF_OK);
    CHECK(size == sizeof(target));

    memset(&io, 0, sizeof(io));
    io.read_source = mem_read;
    io.source_user = &source;
    io.write_target = out_write;
    io.read_target = out_read;
    io.target_user = &out;
    io.progress = progress;

    memset(&out, 0, sizeof(out));
    CHECK(ko_vcdiff_apply(xdelta_patch, sizeof(xdelta_patch), &io) == KO_VCDIFF_OK);
    CHECK(out.len == sizeof(target) && memcmp(out.buf, target, sizeof(target)) == 0);
    CHECK(progress_done == sizeof(target) && progress_total == sizeof(target));

    /* another source fails the window checksum */
    memcpy(wrong, src, sizeof(wrong));
    wrong[2000] ^= 1;
    source.data = wrong;
    memset(&out, 0, sizeof(out));
    CHECK(ko_vcdiff_apply(xdelta_patch, sizeof(xdelta_patch), &io) == KO_VCDIFF_SOURCE_MISMATCH);
    source.data = src;

    /* a source that can't be read, a target that can't be written */
    source.len = 100;
    memset(&out, 0, sizeof(out));
    CHECK(ko_vcdiff_apply(xdelta_patch, sizeof(xdelta_patch), &io) == KO_VCDIFF_READ_ERROR);
    source.len = sizeof(src);
    memset(&out, 0, sizeof(out));
    out.fail_write = 1;
    CHECK(ko_vcdiff_apply(xdelta_patch, sizeof(xdelta_patch), &io) == KO_VCDIFF_WRITE_ERROR);

    memset(&out, 0, sizeof(out));
    cancel = 1;
    io.cancel = &cancel;
    CHECK(ko_vcdiff_apply(xdelta_patch, sizeof(xdelta_patch), &io) == KO_VCDIFF_CANCELLED);
    io.cancel = NULL;

    /* windows that copy from the target written so far */
    memset(&out, 0, sizeof(out));
    CHECK(ko_vcdiff_apply(target_patch, sizeof(target_patch), &io) == KO_VCDIFF_OK);
    CHECK(out.len == 26 && memcmp(out.buf, "hello worldhello world!???", 26) == 0);

    /* not VCDIFF, cut short, secondary compression */
    {
        uint8_t p[sizeof(xdelta_patch)];

        memset(&out, 0, sizeof(out));
        CHECK(ko_vcdiff_apply((const uint8_t*)"PK\3\4 not a patch", 17, &io) == KO_VCDIFF_BAD_PATCH);
        CHECK(ko_vcdiff_apply(xdelta_patch, sizeof(xdelta_patch) - 10, &io) == KO_VCDIFF_BAD_PATCH);
        CHECK(out.len == 0); /* nothing written before the patch was found damaged */
        memcpy(p, xdelta_patch, sizeof(p));
        p[4] |= 1; /* VCD_DECOMPRESS */
        CHECK(ko_vcdiff_apply(p, sizeof(p), &io) == KO_VCDIFF_UNSUPPORTED);
    }
}

