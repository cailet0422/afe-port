#!/usr/bin/env python3
"""Generate the PC build's source list from configure.py.

Runs the project section of configure.py (everything before the
generate_build/progress dispatch) to get config.libs for a game version,
then writes a CMake file that sets:

    DECOMP_C_SOURCES    - sources compiled as C
    DECOMP_CXX_SOURCES  - sources compiled as C++ (.cpp, or -lang=c++)

Libraries that the PC port replaces (Dolphin SDK, Metrowerks runtime, MSL,
MetroTRK, libultra) and individual objects the port provides itself are
left out. Every object of the remaining libraries is included regardless
of its matching status, since the PC build compiles the C sources only.

usage: gen_sources.py VERSION OUT_CMAKE
"""
import os
import re
import sys
from pathlib import Path

# The afe-decomp checkout: the decomp/ submodule unless CMake passes another
ROOT = Path(os.environ.get("AFE_DECOMP_ROOT") or Path(__file__).resolve().parents[2] / "decomp")

# Libraries replaced by the PC port layer.
EXCLUDED_LIBS = {
    "Runtime.PPCEABI.H",
    "MSL_C.PPCEABI.bare.H",
    "TRK_MINNOW_DOLPHIN",
    "libultra",
}

# Individual objects replaced or not needed on PC (paths relative to src/).
EXCLUDED_SOURCES = {
    # REL module entry points; all modules are statically linked on PC.
    "executor.c",
    "fakemain.c",
    # Replaced by pc_os.c / host libc.
    "static/libforest/osreport.c",
    "static/libforest/ReconfigBATs.c",
    "static/libc64/malloc.c",
    "static/libc64/sprintf.c",
    "static/libc64/aprintf.c",
    # GameCube hardware (EXI bus, GBA card unlock DSP task)
    "static/JSystem/JUtility/EXIBios.c",
    "static/jaudio_PP/internal/dsp_cardunlock.c",
    "static/jaudio_PP/internal/dsp_GBAKey.c",
}


def load_config(version):
    source = (ROOT / "configure.py").read_text(encoding="utf-8")
    cut = source.index('if args.mode == "configure":')
    project_part = source[:cut]
    sys.argv = ["configure.py", "--version", version]
    sys.path.insert(0, str(ROOT))
    namespace = {"__name__": "configure_for_pc", "__file__": str(ROOT / "configure.py")}
    exec(compile(project_part, str(ROOT / "configure.py"), "exec"), namespace)
    return namespace["config"]


CXX_MARKERS = re.compile(r'extern "C"|std::|\bnamespace\b|\bclass\b|\btemplate\b|_cast<|::')
INCLUDE_RE = re.compile(r'#include\s+"([^"]+\.c_inc)"')

# Directories whose -lang=c++ sources are built as C on PC when they use no
# C++ features (the PC headers give the shared functions C linkage). g++
# rejects jumps past initializations in switch cases that MWCC accepts.
PREFER_C_DIRS = ("static/jaudio_PP/",)


def uses_cxx(path):
    text = (ROOT / path).read_text(encoding="utf-8", errors="replace")
    if CXX_MARKERS.search(text):
        return True
    for inc in INCLUDE_RE.findall(text):
        inc_path = (ROOT / "include" / inc).resolve()
        if not inc_path.exists():
            inc_path = (ROOT / path).parent / Path(inc).name
        if inc_path.exists() and CXX_MARKERS.search(inc_path.read_text(encoding="utf-8", errors="replace")):
            return True
    return False


def is_cxx(path, flags):
    if path.suffix == ".cpp":
        return True
    if not any(f == "-lang=c++" or f == "-lang c++" for f in flags):
        return False
    rel = path.relative_to("src").as_posix()
    if rel.startswith(PREFER_C_DIRS) and not uses_cxx(path):
        return False
    return True


def main():
    version, out_path = sys.argv[1], Path(sys.argv[2])
    config = load_config(version)

    c_sources, cxx_sources = [], []
    seen = set()
    for lib in config.libs:
        name = lib["lib"]
        if name in EXCLUDED_LIBS or lib.get("progress_category") == "sdk":
            continue
        src_dir = Path(lib.get("src_dir", "src"))
        lib_flags = list(lib.get("cflags", []))
        for obj in lib["objects"]:
            source = obj.options.get("source") or obj.name
            path = src_dir / source
            rel = path.relative_to("src").as_posix()
            if rel in EXCLUDED_SOURCES or rel in seen:
                continue
            if not (ROOT / path).exists():
                print(f"warning: missing source {path}", file=sys.stderr)
                continue
            seen.add(rel)
            flags = lib_flags + list(obj.options.get("cflags") or []) + list(obj.options.get("extra_cflags") or [])
            (cxx_sources if is_cxx(path, flags) else c_sources).append(path.as_posix())

    def block(var, items):
        lines = "\n".join(f'    "${{DECOMP_ROOT}}/{p}"' for p in items)
        return f"set({var}\n{lines}\n)\n"

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        f"# Generated by pc/tools/gen_sources.py for {version}; do not edit.\n"
        + block("DECOMP_C_SOURCES", c_sources)
        + block("DECOMP_CXX_SOURCES", cxx_sources),
        encoding="utf-8",
    )
    print(f"{len(c_sources)} C and {len(cxx_sources)} C++ sources for {version}")


if __name__ == "__main__":
    main()
