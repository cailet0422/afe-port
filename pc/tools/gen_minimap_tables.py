#!/usr/bin/env python3
"""Generate the minimap's acre tables (pc/src/pc_minimap_tables.inc).

The minimap (pc/src/pc_minimap.c) draws the town with the same 32x32 acre
pictures as the game's own map (the pockets map, m_map_ovl.c). Which picture
and palette an acre gets depends on its block type, through three tables that
are static in m_map_ovl.c (l_map_texture, l_map_pal, pluss_bridge), and the
two palettes are static there as well. This script copies them out of the
decomp source, so the minimap shows exactly what the game's map shows, and
resolves the block type names with the enum in m_field_make.h.

Usage:
    python3 pc/tools/gen_minimap_tables.py [--decomp DIR] [--out FILE] [--check]

--check compares with the existing file instead of writing it (exit 1 if it
would change).
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PC_DIR = os.path.dirname(HERE)
ROOT = os.path.dirname(PC_DIR)

# Block types the game's map leaves out (mMP_check_bg_kind) and the defaults
NAMED_TYPES = [
    "BORDER_CLIFF_CORNER_TOP_RIGHT",
    "BORDER_CLIFF_LEFT_TRANSITION",
    "BORDER_CLIFF_RIGHT_TRANSITION",
    "BORDER_CLIFF_LEFT_TUNNEL",
    "BORDER_CLIFF_RIGHT_TUNNEL",
    "FLAT",
    "NUM",
    "NONE",
]


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def block_types(header):
    """name (without mFM_BLOCK_TYPE_) -> value, from the enum in m_field_make.h"""
    body = None
    for m in re.finditer(r"enum\s*\{(.*?)\};", strip_comments(header), flags=re.S):
        if "mFM_BLOCK_TYPE_BORDER_CLIFF_TOP" in m.group(1):
            body = m.group(1)
            break
    if body is None:
        sys.exit("gen_minimap_tables: no mFM_BLOCK_TYPE enum in m_field_make.h")
    values = {}
    value = -1
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        if "=" in item:
            name, expr = (s.strip() for s in item.split("=", 1))
            value = int(expr, 0)
        else:
            name = item
            value += 1
        if not name.startswith("mFM_BLOCK_TYPE_"):
            sys.exit("gen_minimap_tables: unexpected enum member %r" % name)
        values[name[len("mFM_BLOCK_TYPE_"):]] = value
    return values


def table(source, decl):
    """The initializer items of `decl ... = { ... };` in source (comments removed)"""
    m = re.search(re.escape(decl) + r"[^=]*=\s*\{(.*?)\};", strip_comments(source), flags=re.S)
    if m is None:
        sys.exit("gen_minimap_tables: %s not found in m_map_ovl.c" % decl)
    return [s.strip() for s in m.group(1).split(",") if s.strip()]


def generate(decomp):
    with open(os.path.join(decomp, "include", "m_field_make.h"), encoding="utf-8") as f:
        types = block_types(f.read())
    with open(os.path.join(decomp, "src", "game", "m_map_ovl.c"), encoding="utf-8") as f:
        source = f.read()

    count = types["NUM"]
    textures = table(source, "static u8* l_map_texture[mFM_BLOCK_TYPE_NUM]")
    pals = [int(v, 0) for v in table(source, "static u8 l_map_pal[mFM_BLOCK_TYPE_NUM]")]
    bridges = table(source, "static u8 pluss_bridge[mFM_BLOCK_TYPE_NUM]")
    palettes = [[int(v, 0) for v in table(source, "static u16 kan_tizu%d_pal[16]" % (i + 1))] for i in range(2)]

    for name, items in (("l_map_texture", textures), ("l_map_pal", pals), ("pluss_bridge", bridges)):
        if len(items) != count:
            sys.exit("gen_minimap_tables: %s has %d entries, mFM_BLOCK_TYPE_NUM is %d" % (name, len(items), count))
    for i, pal in enumerate(palettes):
        if len(pal) != 16:
            sys.exit("gen_minimap_tables: kan_tizu%d_pal has %d entries" % (i + 1, len(pal)))
    if any(p not in (0, 1) for p in pals):
        sys.exit("gen_minimap_tables: l_map_pal names a palette other than 0 and 1")

    unique = []
    for t in textures:
        if not re.fullmatch(r"kan_tizu_\w+_TA_tex_txt", t):
            sys.exit("gen_minimap_tables: unexpected texture %r" % t)
        if t not in unique:
            unique.append(t)

    bridge_values = []
    for b in bridges:
        if not b.startswith("mFM_BLOCK_TYPE_") or b[len("mFM_BLOCK_TYPE_"):] not in types:
            sys.exit("gen_minimap_tables: unexpected bridge entry %r" % b)
        bridge_values.append(types[b[len("mFM_BLOCK_TYPE_"):]])

    by_value = {}
    for name, value in types.items():
        by_value.setdefault(value, name)

    out = []
    out.append("/* Generated by pc/tools/gen_minimap_tables.py from the decomp's m_map_ovl.c")
    out.append(" * (l_map_texture, l_map_pal, pluss_bridge, kan_tizu1_pal, kan_tizu2_pal)")
    out.append(" * and m_field_make.h. Do not edit; run the script again instead. */")
    out.append("")
    for name in NAMED_TYPES:
        out.append("#define PC_MINIMAP_BT_%s %d" % (name, types[name]))
    out.append("#define PC_MINIMAP_TEX_NUM %d" % len(unique))
    out.append("")
    out.append("/* The acre pictures, in the order of the index tables below */")
    out.append("#define PC_MINIMAP_TEXTURES(X) \\")
    for i, t in enumerate(unique):
        out.append("    X(%s)%s" % (t, " \\" if i + 1 < len(unique) else ""))
    out.append("")
    out.append("#ifdef PC_MINIMAP_TABLE_DATA")
    out.append("/* By block type: the picture (index into PC_MINIMAP_TEXTURES), the palette,")
    out.append(" * and the block type that has the bridge (PC_MINIMAP_BT_NONE: none) */")
    out.append("static const unsigned char s_type_tex[PC_MINIMAP_BT_NUM] = {")
    for v, t in enumerate(textures):
        out.append("    %d, /* %s */" % (unique.index(t), by_value.get(v, "?")))
    out.append("};")
    out.append("")
    out.append("static const unsigned char s_type_pal[PC_MINIMAP_BT_NUM] = {")
    for v, p in enumerate(pals):
        out.append("    %d, /* %s */" % (p, by_value.get(v, "?")))
    out.append("};")
    out.append("")
    out.append("static const unsigned char s_type_bridge[PC_MINIMAP_BT_NUM] = {")
    for v, b in enumerate(bridge_values):
        out.append("    %d, /* %s -> %s */" % (b, by_value.get(v, "?"), by_value.get(b, "?")))
    out.append("};")
    out.append("")
    out.append("/* RGB5A3, as the game loads them (host byte order) */")
    out.append("static const unsigned short s_palettes[2][16] = {")
    for pal in palettes:
        out.append("    { " + ", ".join("0x%04X" % v for v in pal) + " },")
    out.append("};")
    out.append("#endif")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--decomp", default=os.path.join(ROOT, "decomp"))
    parser.add_argument("--out", default=os.path.join(PC_DIR, "src", "pc_minimap_tables.inc"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = generate(args.decomp)
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as f:
                old = f.read()
        except OSError:
            old = None
        if old != text:
            print("%s is out of date; run pc/tools/gen_minimap_tables.py" % args.out)
            return 1
        print("%s is up to date" % args.out)
        return 0
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
