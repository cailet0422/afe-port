#!/usr/bin/env python3
"""Write the 2,350 Hangul syllables of KS X 1001 in code order.

The Korean patch numbers its glyphs in this order (docs/pc_port/korean_patch.md),
which is also Unicode order. The syllables are rows 0x30-0x48 of KS X 1001
(EUC-KR 0xB0A1-0xC8FE).

usage: gen_ksx1001.py > pc/src/ko/ko_ksx1001.inc
"""

syllables = [ord(bytes([row, col]).decode("euc-kr")) for row in range(0xB0, 0xC9) for col in range(0xA1, 0xFF)]
assert syllables == sorted(syllables)
assert len(syllables) == 2350

print("/* Generated by pc/tools/gen_ksx1001.py: KS X 1001 Hangul syllables in order */")
for i in range(0, len(syllables), 12):
    print("    " + " ".join(f"0x{cp:04X}," for cp in syllables[i:i + 12]))
