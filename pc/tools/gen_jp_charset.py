#!/usr/bin/env python3
"""Writes pc/src/jp_charset.c: the original disc's characters as Unicode.

The Japanese どうぶつの森 e+ draws text from three font pages: the kana and
signs (one byte each), and two pages of kanji and icons that a string reaches
through its kanji tags (m_font). afe-decomp's include/charmap.h names every
code of the three ("e+ font": CHAR_PP_nnn, CHAR_PP_KANJI0_nnn,
CHAR_PP_KANJI1_nnn, each with the character in a comment); this turns those
comments into a table. Half-width brackets and the middle dot become their
full-width forms (as the game's font draws them); icons get the nearest sign,
or none (0) when there is no such sign; control codes and tags are 0.

    python3 pc/tools/gen_jp_charset.py           # write pc/src/jp_charset.c
    python3 pc/tools/gen_jp_charset.py --check   # fail if it would change (CI)
    python3 pc/tools/gen_jp_charset.py --chars   # print the characters (the font's subset)

DECOMP_ROOT=/path/to/afe-decomp picks a decomp other than the submodule.
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
# the decomp: the submodule, or DECOMP_ROOT (as CMake's) when that is elsewhere
CHARMAP = os.path.join(os.environ.get("DECOMP_ROOT") or os.path.join(ROOT, "decomp"), "include", "charmap.h")
OUT = os.path.join(ROOT, "pc", "src", "jp_charset.c")

# comments that are not the character itself
NAMED = {
    "(space)": 0x20, "heart": 0x2665, "smile": 0x263A, "star": 0x2605, "multiply": 0x00D7, "division": 0x00F7,
    # (signs the menu fonts lack: no tofu in a button)
    "letter": 0, "sun": 0, "cloud": 0, "umbrella": 0, "snowman": 0,
    "clover": 0x2663, "circle": 0x25CB, "cross": 0x2715, "square": 0x25A1, "triangle": 0x25B3,
    "water droplet": 0, "anger symbol": 0, "control code": 0, "message tag": 0, "\\n": 0, "surprise": 0,
    "laugh": 0, "angry": 0, "scared": 0, "paw prints": 0, "key": 0, "bell bag": 0, "wind": 0, "dog": 0,
    "cat": 0, "rabbit": 0, "bird": 0, "cow": 0, "pig": 0, "fish": 0, "insect": 0, "skull": 0, "Gyroid": 0,
    "(unused)": 0,
}
# half-width forms the font draws full width
WIDEN = {0xFF62: 0x300C, 0xFF63: 0x300D, 0xFF65: 0x30FB, 0xFF61: 0x3002, 0xFF64: 0x3001}


def table():
    with open(CHARMAP, encoding="utf-8") as f:
        text = f.read()
    text = text[text.index("/* e+ font */"):]
    pages = [[0] * 256 for _ in range(3)]
    seen = 0
    for m in re.finditer(r"#define CHAR_PP_(?:KANJI(\d)_)?\d+\s+(\d+)\s*//\s*(.*)", text):
        page = 0 if m.group(1) is None else int(m.group(1)) + 1
        code = int(m.group(2))
        name = m.group(3).strip()
        if name in NAMED:
            u = NAMED[name]
        elif len(name) == 1:
            u = WIDEN.get(ord(name), ord(name))
        else:
            raise SystemExit(f"charmap.h: no Unicode for page {page} code {code}: {name!r}")
        pages[page][code] = u
        seen += 1
    if seen != 768:
        raise SystemExit(f"charmap.h: {seen} codes of the e+ font, 768 expected")
    return pages


def render(pages):
    out = [
        "/* jp_charset.c - the original disc's font pages as Unicode (0: none).",
        " * Generated by pc/tools/gen_jp_charset.py from afe-decomp's include/charmap.h;",
        " * do not edit. Page 0: the kana and signs; 1 and 2: the kanji pages a kanji",
        " * tag selects (m_font: mFont_TEX_TYPE_FONT2, FONT3). */",
        '#include "jp_charset.h"',
        "",
        "const uint16_t jp_charset[3][256] = {",
    ]
    for p in pages:
        out.append("    {")
        for i in range(0, 256, 8):
            out.append("        " + ", ".join(f"0x{u:04X}" for u in p[i:i + 8]) + ",")
        out.append("    },")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    pages = table()
    if "--chars" in sys.argv[1:]:
        sys.stdout.write("".join(sorted({chr(u) for p in pages for u in p if u > 0x20})))
        return 0
    text = render(pages)
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("pc/src/jp_charset.c is out of date: python3 pc/tools/gen_jp_charset.py")
                return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
